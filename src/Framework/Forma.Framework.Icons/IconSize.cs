namespace Forma.Framework.Icons;

/// <summary>The size an icon is drawn at.</summary>
public enum IconSize
{
    /// <summary>The size of the surrounding text, for a glyph inline with it.</summary>
    Inline,

    /// <summary>The size of a glyph on a button, in a toolbar or in a dense row.</summary>
    Small,

    /// <summary>The size of a glyph that leads a panel, a tile or a picker cell.</summary>
    Medium,

    /// <summary>The size of a section's figure.</summary>
    Large,

    /// <summary>The size of the figure of an empty state, a drop zone or a media facade.</summary>
    Display,
}
