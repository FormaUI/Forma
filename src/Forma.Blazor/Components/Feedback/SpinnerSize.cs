namespace Forma.Blazor.Components.Feedback;

/// <summary>The size a <see cref="FormaSpinner"/> draws its ring at.</summary>
public enum SpinnerSize
{
    /// <summary>A compact ring for inline use, such as inside a grid cell.</summary>
    Small,

    /// <summary>Standard sizing for a spinner that stands on its own.</summary>
    Medium,

    /// <summary>An enlarged ring for a surface with nothing else to anchor attention.</summary>
    Large
}
